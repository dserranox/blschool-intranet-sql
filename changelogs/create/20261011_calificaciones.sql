-- =======================
-- CALIFICACIONES
--   LOGROS: configuración por curso (pesos que suman 100)
--   EVALUACIONES: Parcial / Final (una por comisión) y pruebas (las crea la docente)
--   EVALUACION_LOGROS: copia congelada de los logros al crear Parcial/Final
--   CALIFICACIONES: nota por alumno y evaluación (Parcial/Final = suma de aportes)
--   CALIFICACION_LOGROS: aporte de cada logro (0 .. peso)
-- =======================
CREATE TABLE IF NOT EXISTS LOGROS (
  LOG_ID BIGSERIAL PRIMARY KEY,
  LOG_CUR_ID BIGINT NOT NULL REFERENCES CURSOS(CUR_ID) ON DELETE CASCADE,
  LOG_NOMBRE VARCHAR(100) NOT NULL,
  LOG_PESO NUMERIC(5,2) NOT NULL,
  LOG_ORDEN INT NOT NULL,

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_log_peso CHECK (LOG_PESO > 0 AND LOG_PESO <= 100)
);
CREATE INDEX IF NOT EXISTS ix_log_curso ON LOGROS(LOG_CUR_ID);

CREATE TABLE IF NOT EXISTS EVALUACIONES (
  EVA_ID BIGSERIAL PRIMARY KEY,
  EVA_COM_ID BIGINT NOT NULL REFERENCES COMISIONES(COM_ID) ON DELETE CASCADE,
  EVA_TIPO VARCHAR(10) NOT NULL,
  EVA_NOMBRE VARCHAR(100) NOT NULL,
  EVA_FECHA DATE,
  EVA_ETAPA INT,

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_eva_tipo CHECK (EVA_TIPO IN ('PARCIAL', 'FINAL', 'PRUEBA')),
  CONSTRAINT ck_eva_etapa CHECK (EVA_ETAPA IS NULL OR EVA_ETAPA IN (1, 2)),
  CONSTRAINT ck_eva_prueba CHECK (EVA_TIPO <> 'PRUEBA' OR (EVA_FECHA IS NOT NULL AND EVA_ETAPA IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_eva_comision ON EVALUACIONES(EVA_COM_ID);
-- Un solo Parcial y un solo Final por comisión
CREATE UNIQUE INDEX IF NOT EXISTS uq_eva_parcial_final
  ON EVALUACIONES(EVA_COM_ID, EVA_TIPO) WHERE EVA_TIPO IN ('PARCIAL', 'FINAL');

CREATE TABLE IF NOT EXISTS EVALUACION_LOGROS (
  ELO_ID BIGSERIAL PRIMARY KEY,
  ELO_EVA_ID BIGINT NOT NULL REFERENCES EVALUACIONES(EVA_ID) ON DELETE CASCADE,
  ELO_NOMBRE VARCHAR(100) NOT NULL,
  ELO_PESO NUMERIC(5,2) NOT NULL,
  ELO_ORDEN INT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_elo_evaluacion ON EVALUACION_LOGROS(ELO_EVA_ID);

CREATE TABLE IF NOT EXISTS CALIFICACIONES (
  CAL_ID BIGSERIAL PRIMARY KEY,
  CAL_EVA_ID BIGINT NOT NULL REFERENCES EVALUACIONES(EVA_ID) ON DELETE CASCADE,
  CAL_ALU_PER_ID BIGINT NOT NULL REFERENCES ALUMNOS(ALU_PER_ID) ON DELETE CASCADE,
  CAL_NOTA NUMERIC(5,2),
  CAL_AUSENTE BOOLEAN NOT NULL DEFAULT FALSE,

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_cal_nota CHECK (CAL_NOTA IS NULL OR (CAL_NOTA >= 0 AND CAL_NOTA <= 100))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_cal_eva_alumno ON CALIFICACIONES(CAL_EVA_ID, CAL_ALU_PER_ID);
CREATE INDEX IF NOT EXISTS ix_cal_alumno ON CALIFICACIONES(CAL_ALU_PER_ID);

CREATE TABLE IF NOT EXISTS CALIFICACION_LOGROS (
  CLO_ID BIGSERIAL PRIMARY KEY,
  CLO_CAL_ID BIGINT NOT NULL REFERENCES CALIFICACIONES(CAL_ID) ON DELETE CASCADE,
  CLO_ELO_ID BIGINT NOT NULL REFERENCES EVALUACION_LOGROS(ELO_ID) ON DELETE CASCADE,
  CLO_VALOR NUMERIC(5,2) NOT NULL,

  CONSTRAINT ck_clo_valor CHECK (CLO_VALOR >= 0)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_clo_cal_elo ON CALIFICACION_LOGROS(CLO_CAL_ID, CLO_ELO_ID);

-- Permisos (la restricción "sólo sus comisiones" la aplica el backend)
INSERT INTO PERMISOS (PRM_CLAVE, PRM_DESCRIPCION)
VALUES
  ('CALIFICACIONES:READ',  'Ver calificaciones'),
  ('CALIFICACIONES:WRITE', 'Cargar/corregir calificaciones')
ON CONFLICT (PRM_CLAVE) DO NOTHING;

INSERT INTO ROLES_PERMISOS (RP_ROL_ID, RP_PRM_ID)
SELECT r.ROL_ID, p.PRM_ID
FROM ROLES r
JOIN PERMISOS p ON p.PRM_CLAVE IN ('CALIFICACIONES:READ', 'CALIFICACIONES:WRITE')
WHERE r.ROL_NOMBRE IN ('ADMIN', 'DOCENTE')
ON CONFLICT DO NOTHING;
