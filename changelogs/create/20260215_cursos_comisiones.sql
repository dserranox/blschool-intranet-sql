-- =======================
-- CURSOS
-- =======================
CREATE TABLE IF NOT EXISTS CURSOS (
  CUR_ID BIGSERIAL PRIMARY KEY,
  CUR_CODIGO VARCHAR(50) NOT NULL,
  CUR_NOMBRE VARCHAR(150) NOT NULL,
  CUR_DESCRIPCION VARCHAR(300),

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_cursos_codigo ON CURSOS(CUR_CODIGO);

-- =======================
-- COMISIONES (por año)
-- =======================
CREATE TABLE IF NOT EXISTS COMISIONES (
  COM_ID BIGSERIAL PRIMARY KEY,
  COM_CUR_ID BIGINT NOT NULL REFERENCES CURSOS(CUR_ID),
  COM_ANIO INT NOT NULL,
  COM_NOMBRE VARCHAR(100) NOT NULL,     -- A, B, C...
  COM_CUPO INT NOT NULL,
  COM_ACTIVA BOOLEAN NOT NULL DEFAULT TRUE,

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =======================
-- CLASES / HORARIOS DE COMISION
-- =======================
CREATE TABLE IF NOT EXISTS COMISION_CLASES (
  CLC_ID BIGSERIAL PRIMARY KEY,
  CLC_COM_ID BIGINT NOT NULL REFERENCES COMISIONES(COM_ID) ON DELETE CASCADE,
  CLC_DIA_SEMANA INT NOT NULL,        -- 1=Lun ... 7=Dom (definilo igual en backend)
  CLC_HORA_DESDE TIME NOT NULL,
  CLC_HORA_HASTA TIME NOT NULL,
  CLC_DOCENTE_ID BIGINT REFERENCES PERSONAS(PER_ID),
  CLC_DOCENTE_ID_SUPLENTE BIGINT REFERENCES PERSONAS(PER_ID),

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_clc_horas CHECK (CLC_HORA_HASTA > CLC_HORA_DESDE),
  CONSTRAINT ck_clc_dia CHECK (CLC_DIA_SEMANA BETWEEN 1 AND 7)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_clc_horario
  ON COMISION_CLASES(CLC_COM_ID, CLC_DIA_SEMANA, CLC_HORA_DESDE, CLC_HORA_HASTA);

-- =======================
-- INSCRIPCIONES (histórico)
-- =======================
CREATE TABLE IF NOT EXISTS INSCRIPCIONES (
  INS_ID BIGSERIAL PRIMARY KEY,
  INS_ALU_PER_ID BIGINT NOT NULL REFERENCES ALUMNOS(ALU_PER_ID),
  INS_COM_ID BIGINT NOT NULL REFERENCES COMISIONES(COM_ID),
  INS_FECHA timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INS_ESTADO VARCHAR(20) NOT NULL DEFAULT 'ACTIVA'  -- ACTIVA | INACTIVO
);

CREATE INDEX IF NOT EXISTS ix_ins_comision ON INSCRIPCIONES(INS_COM_ID);