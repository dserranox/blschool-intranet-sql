-- =======================
-- PREINSCRIPCIONES (por año, desde Google Forms o carga manual)
--   Un alumno puede tener una sola preinscripción por año.
--   El administrador la asigna después a una comisión de ese año,
--   lo que genera la INSCRIPCION correspondiente (PRE_INS_ID).
-- =======================
CREATE TABLE IF NOT EXISTS PREINSCRIPCIONES (
  PRE_ID BIGSERIAL PRIMARY KEY,
  PRE_ALU_PER_ID BIGINT NOT NULL REFERENCES ALUMNOS(ALU_PER_ID) ON UPDATE CASCADE ON DELETE CASCADE,
  PRE_ANIO INT NOT NULL,
  PRE_FECHA_FORMULARIO TIMESTAMP,                       -- "Marca temporal" del Google Form
  PRE_ESCUELA_CURSO_TURNO VARCHAR(300),                 -- texto libre del formulario
  PRE_ALUMNO_NUEVO BOOLEAN NOT NULL DEFAULT FALSE,      -- el alumno fue creado por esta preinscripción
  PRE_ESTADO VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',  -- PENDIENTE | ASIGNADA | DESCARTADA
  PRE_COM_ID BIGINT REFERENCES COMISIONES(COM_ID) ON DELETE SET NULL,
  PRE_INS_ID BIGINT REFERENCES INSCRIPCIONES(INS_ID) ON DELETE SET NULL,
  PRE_ORIGEN VARCHAR(30) NOT NULL DEFAULT 'GOOGLE_FORM', -- GOOGLE_FORM | MANUAL
  PRE_DATOS_FORMULARIO TEXT,                            -- respuesta original completa (JSON)

  aud_usr_ins varchar(250) NOT NULL,
  aud_usr_upd varchar(250) NOT NULL,
  aud_fecha_ins timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  aud_fecha_upd timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,

  CONSTRAINT ck_pre_estado CHECK (PRE_ESTADO IN ('PENDIENTE', 'ASIGNADA', 'DESCARTADA'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_pre_alumno_anio ON PREINSCRIPCIONES(PRE_ALU_PER_ID, PRE_ANIO);
CREATE INDEX IF NOT EXISTS ix_pre_anio_estado ON PREINSCRIPCIONES(PRE_ANIO, PRE_ESTADO);

-- Historial de inscripciones por alumno
CREATE INDEX IF NOT EXISTS ix_ins_alumno ON INSCRIPCIONES(INS_ALU_PER_ID);

-- Permisos del nuevo módulo (ADMIN escribe, DOCENTE sólo lee)
INSERT INTO PERMISOS (PRM_CLAVE, PRM_DESCRIPCION)
VALUES
  ('PREINSCRIPCIONES:READ',  'Ver/consultar preinscripciones'),
  ('PREINSCRIPCIONES:WRITE', 'Asignar/descartar preinscripciones')
ON CONFLICT (PRM_CLAVE) DO NOTHING;

INSERT INTO ROLES_PERMISOS (RP_ROL_ID, RP_PRM_ID)
SELECT r.ROL_ID, p.PRM_ID
FROM ROLES r
JOIN PERMISOS p ON p.PRM_CLAVE IN ('PREINSCRIPCIONES:READ', 'PREINSCRIPCIONES:WRITE')
WHERE r.ROL_NOMBRE = 'ADMIN'
ON CONFLICT DO NOTHING;

INSERT INTO ROLES_PERMISOS (RP_ROL_ID, RP_PRM_ID)
SELECT r.ROL_ID, p.PRM_ID
FROM ROLES r
JOIN PERMISOS p ON p.PRM_CLAVE = 'PREINSCRIPCIONES:READ'
WHERE r.ROL_NOMBRE = 'DOCENTE'
ON CONFLICT DO NOTHING;
