-- =======================
-- AUDITORIA (Hibernate Envers)
--   REVISIONES: una fila por transacción que cambió algún dato auditado (quién y cuándo).
--   <TABLA>_AUD: una fila por cada versión de un registro, con los valores que quedaron.
--     REV     -> revisión (REVISIONES.REV_ID)
--     REVTYPE -> 0 = alta, 1 = modificación, 2 = baja (en las bajas se guardan los últimos valores)
--   Las columnas AUD_* de las tablas originales no se copian (el usuario/fecha está en REVISIONES).
--   Sin FK a las tablas originales: el historial tiene que sobrevivir a los borrados.
-- =======================
CREATE TABLE IF NOT EXISTS REVISIONES (
  REV_ID BIGSERIAL PRIMARY KEY,
  REV_FECHA TIMESTAMP NOT NULL,
  REV_USUARIO VARCHAR(250) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_rev_fecha ON REVISIONES(REV_FECHA);

-- PERSONAS
CREATE TABLE IF NOT EXISTS PERSONAS_AUD (
  PER_ID BIGINT NOT NULL,
  REV BIGINT NOT NULL REFERENCES REVISIONES(REV_ID),
  REVTYPE SMALLINT,
  PER_NOMBRES VARCHAR(150),
  PER_APELLIDO VARCHAR(150),
  PER_FECHA_NACIMIENTO DATE,
  PER_DNI VARCHAR(20),
  PER_EMAIL VARCHAR(200),
  PER_DIRECCION VARCHAR(250),
  PRIMARY KEY (PER_ID, REV)
);
CREATE INDEX IF NOT EXISTS ix_per_aud_rev ON PERSONAS_AUD(REV);

-- PERSONAS_TELEFONOS
CREATE TABLE IF NOT EXISTS PERSONAS_TELEFONOS_AUD (
  PTE_ID BIGINT NOT NULL,
  REV BIGINT NOT NULL REFERENCES REVISIONES(REV_ID),
  REVTYPE SMALLINT,
  PTE_PER_ID BIGINT,
  PTE_NUMERO VARCHAR(30),
  PTE_TIPO VARCHAR(30),
  PTE_NOTA VARCHAR(100),
  PTE_PRINCIPAL BOOLEAN,
  PRIMARY KEY (PTE_ID, REV)
);
CREATE INDEX IF NOT EXISTS ix_pte_aud_rev ON PERSONAS_TELEFONOS_AUD(REV);
CREATE INDEX IF NOT EXISTS ix_pte_aud_persona ON PERSONAS_TELEFONOS_AUD(PTE_PER_ID);

-- ALUMNOS
CREATE TABLE IF NOT EXISTS ALUMNOS_AUD (
  ALU_PER_ID BIGINT NOT NULL,
  REV BIGINT NOT NULL REFERENCES REVISIONES(REV_ID),
  REVTYPE SMALLINT,
  ALU_ESCUELA VARCHAR(200),
  ALU_GRADO_CURSO VARCHAR(100),
  ALU_EMAIL_ALTERNATIVO VARCHAR(200),
  ALU_ESTADO VARCHAR(100),
  ALU_PROBLEMA_SALUD VARCHAR(500),
  PRIMARY KEY (ALU_PER_ID, REV)
);
CREATE INDEX IF NOT EXISTS ix_alu_aud_rev ON ALUMNOS_AUD(REV);

-- CALIFICACIONES
CREATE TABLE IF NOT EXISTS CALIFICACIONES_AUD (
  CAL_ID BIGINT NOT NULL,
  REV BIGINT NOT NULL REFERENCES REVISIONES(REV_ID),
  REVTYPE SMALLINT,
  CAL_EVA_ID BIGINT,
  CAL_ALU_PER_ID BIGINT,
  CAL_NOTA NUMERIC(5,2),
  CAL_AUSENTE BOOLEAN,
  PRIMARY KEY (CAL_ID, REV)
);
CREATE INDEX IF NOT EXISTS ix_cal_aud_rev ON CALIFICACIONES_AUD(REV);
CREATE INDEX IF NOT EXISTS ix_cal_aud_alumno ON CALIFICACIONES_AUD(CAL_ALU_PER_ID);

-- CALIFICACION_LOGROS
CREATE TABLE IF NOT EXISTS CALIFICACION_LOGROS_AUD (
  CLO_ID BIGINT NOT NULL,
  REV BIGINT NOT NULL REFERENCES REVISIONES(REV_ID),
  REVTYPE SMALLINT,
  CLO_CAL_ID BIGINT,
  CLO_ELO_ID BIGINT,
  CLO_VALOR NUMERIC(5,2),
  PRIMARY KEY (CLO_ID, REV)
);
CREATE INDEX IF NOT EXISTS ix_clo_aud_rev ON CALIFICACION_LOGROS_AUD(REV);
CREATE INDEX IF NOT EXISTS ix_clo_aud_calificacion ON CALIFICACION_LOGROS_AUD(CLO_CAL_ID);
